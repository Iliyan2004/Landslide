#!/usr/bin/env python3
"""Parse the D01-D40 table in the methodology doc into data_registry.yaml and licensing_register.csv.

Run: python scripts/build_registries.py
Keeps the machine-readable registry in lock-step with the methodology (no hand retyping).
"""
import csv, re, sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "LANDSLIDE_PLATFORM_FULL_METHODOLOGY.md"

ACCESS = {"P": "public", "R": "free_registration_or_api_key", "C": "conditional_verify_terms",
          "L": "local_field_not_public", "O": "optional"}
PRIORITY = {"A": "base_minimum", "B": "advanced_engine", "C": "local_specialized"}


def split_codes(s):
    return [c for c in re.split(r"[/,\s]+", s) if len(c) == 1 and c.isupper()]


def main():
    rows = []
    for line in DOC.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*(D\d{2})\s*\|", line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 6:
            sys.exit(f"Unexpected column count in: {line[:80]}")
        did, src, native, why, access, prio = cells
        name = re.sub(r"\*\*", "", src.split("—")[0]).strip()
        urls = re.findall(r"https?://[^\s;)]+", src)
        raw_access = [a for a in split_codes(access) if a in ACCESS]
        rows.append({
            "id": did,
            "name": name,
            "source_text": re.sub(r"\*\*", "", src),
            "urls": urls,
            "native_data_resolution": native,
            "purpose": why,
            "access_codes": split_codes(access),
            "access": [ACCESS[a] for a in raw_access],
            "priority_codes": split_codes(prio),
            "priority": [PRIORITY[p] for p in split_codes(prio) if p in PRIORITY],
            "requires_credentials": any(a == "R" for a in raw_access),
            "automatable": not any(a == "L" for a in raw_access),
            # Fields the methodology (§13) requires per raw source; filled at acquisition time.
            "version": None, "acquired_utc": None, "native_crs": None,
            "units": None, "uncertainty_note": None, "sha256": None,
            "licence_checked": False, "commercial_use_permitted": None,
        })
    if len(rows) != 40:
        sys.exit(f"Expected 40 registry rows, parsed {len(rows)}")
    (ROOT / "docs" / "data_registry.yaml").write_text(
        "# GENERATED by scripts/build_registries.py from the methodology D01-D40 table.\n"
        + yaml.safe_dump({"sources": rows}, sort_keys=False, allow_unicode=True, width=100),
        encoding="utf-8")
    with open(ROOT / "docs" / "licensing_register.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "name", "access_codes", "urls", "licence_checked", "licence_name",
                    "redistribution_allowed", "commercial_integration_allowed", "attribution_text",
                    "checked_by", "checked_date", "notes"])
        for r in rows:
            w.writerow([r["id"], r["name"], "/".join(r["access_codes"]), " ".join(r["urls"]),
                        "no", "", "", "", "", "", "", "VERIFY BEFORE DEPLOYMENT"])
    print(f"wrote {len(rows)} sources")


if __name__ == "__main__":
    main()
